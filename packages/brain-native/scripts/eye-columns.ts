// Writes src/eye_columns.cpp, the eyes' column table, from the TypeScript's
// (packages/brain/src/eye-columns.ts), so the two are the same data:
//
//   node packages/brain-native/scripts/eye-columns.ts           rewrite it
//   node packages/brain-native/scripts/eye-columns.ts --check   exit 1 if it is not what this would write
//
// tests/eyes.test.ts fails while the file and the TypeScript's table differ.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COLUMN_KINDS, EYE_COLUMNS } from "../../brain/src/eye-columns.ts";
import type { EyeColumn } from "../../brain/src/eye-columns.ts";

export const EYE_COLUMNS_SOURCE = fileURLToPath(new URL("../src/eye_columns.cpp", import.meta.url));

const whole = (x: number, max: number) => Number.isInteger(x) && x >= 0 && x <= max;

/** The C++ source of the table. */
export function eyeColumnsSource(): string {
  const rows = (side: "left" | "right") =>
    EYE_COLUMNS[side]
      .map((row: EyeColumn) => {
        const [hex1, hex2, kind, ...cells] = row;
        // The C++ table holds these as bytes and 32-bit IDs.
        if (!whole(hex1, 255) || !whole(hex2, 255) || !whole(kind, COLUMN_KINDS.length - 1) || !cells.every((id) => whole(id, 0xffffffff))) {
          throw new Error(`A ${side} column doesn't fit the C++ table: ${row.join(", ")}`);
        }
        return `    {${row.join(", ")}},\n`;
      })
      .join("");
  return `// Generated by scripts/eye-columns.ts from packages/brain/src/eye-columns.ts,
// whose comment says where the data comes from (the FlyEM male CNS
// connectome and its optic column assignments, CC-BY 4.0). Do not edit:
// regenerate it, and tests/eyes.test.ts fails while the two differ.
//
// A row is {hex1, hex2, kind, L1, L2, L3}: kind indexes ${COLUMN_KINDS.join(", ")}, and
// a body ID of 0 means the column has no such cell.

#include "eyes.hpp"

namespace fly::eyes {

namespace {

constexpr EyeColumn kLeft[] = {
${rows("left")}};

constexpr EyeColumn kRight[] = {
${rows("right")}};

}  // namespace

const Columns kEyeColumns{kLeft, kRight};

}  // namespace fly::eyes
`;
}

if (import.meta.main) {
  const source = eyeColumnsSource();
  if (process.argv.includes("--check")) {
    if (readFileSync(EYE_COLUMNS_SOURCE, "utf8") !== source) {
      console.error(`${EYE_COLUMNS_SOURCE} is out of date: run node packages/brain-native/scripts/eye-columns.ts`);
      process.exit(1);
    }
  } else {
    writeFileSync(EYE_COLUMNS_SOURCE, source);
  }
}
