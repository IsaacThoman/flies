// Generates the native table from the reference; --check refuses stale data.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ORN_TABLE } from "../../brain/src/orn-table.ts";

export const ORN_TABLE_SOURCE = fileURLToPath(new URL("../src/orn_table.cpp", import.meta.url));
export function ornTableSource(): string {
  const rows = ORN_TABLE.map(([g, unit, source, spontaneous, answers]) => {
    if (answers.length !== 5 || ![spontaneous, ...answers].every(Number.isFinite)) throw new Error(`Invalid ORN row ${g}`);
    return `    {${JSON.stringify(g)}, ${JSON.stringify(unit)}, ${JSON.stringify(source)}, ${spontaneous}, {${answers.join(", ")}}},`;
  }).join("\n");
  return `// Generated by scripts/orn-table.ts from packages/brain/src/orn-table.ts.
// That table cites DoOR.data (Münch & Galizia 2016, CC BY-SA 4.0).
// Do not edit; tests/olfaction.test.ts checks the reference data.
#include "olfaction.hpp"
namespace fly::olfaction {
namespace {
constexpr Row kRows[] = {
${rows}
};
}
const std::span<const Row> kTable{kRows};
}  // namespace fly::olfaction
`;
}
if (import.meta.main) {
  const source = ornTableSource();
  if (process.argv.includes("--check")) {
    if (readFileSync(ORN_TABLE_SOURCE, "utf8") !== source) {
      console.error("ORN table is out of date: run node packages/brain-native/scripts/orn-table.ts");
      process.exit(1);
    }
  } else writeFileSync(ORN_TABLE_SOURCE, source);
}
